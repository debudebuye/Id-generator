#!/usr/bin/env python3
"""
Setup script for Telegram Bot Access Control
This script helps you configure which users can access your Telegram bot
"""

import os
import sys
from pathlib import Path

def get_user_input(prompt: str, default: str = "") -> str:
    """Get user input with a default value"""
    if default:
        user_input = input(f"{prompt} [{default}]: ").strip()
        return user_input if user_input else default
    return input(f"{prompt}: ").strip()

def create_env_file():
    """Create or update .env file with Telegram bot configuration"""
    env_path = Path(".env")
    
    print("🔐 Setting up Telegram Bot Access Control")
    print("=" * 50)
    
    # Get bot token
    bot_token = get_user_input("Enter your Telegram Bot Token (from @BotFather)")
    if not bot_token:
        print("❌ Bot token is required!")
        return False
    
    # Get allowed user IDs
    print("\n👥 Access Control Setup:")
    print("You can restrict access to specific users only.")
    print("To get a user ID, use the get_telegram_user_id.py script")
    
    user_ids_input = get_user_input(
        "Enter allowed user IDs (comma-separated, e.g., 123456789,987654321)",
        "123456789,987654321"
    )
    
    # Parse user IDs
    if user_ids_input:
        try:
            user_ids = [int(uid.strip()) for uid in user_ids_input.split(',') if uid.strip()]
            if not user_ids:
                raise ValueError("No valid user IDs found")
        except ValueError as e:
            print(f"❌ Error parsing user IDs: {e}")
            return False
    else:
        user_ids = []
    
    # Create .env content
    env_content = f"""# Environment variables for Fyda ID Card Generator
# Generated by setup_access_control.py

# Flask configuration
FLASK_ENV=development
FLASK_APP=app.py

# Security (use a simple key for development)
SECRET_KEY=dev-secret-key-change-in-production

# CORS settings (allow all in development)
CORS_ORIGINS=http://localhost:5000,http://127.0.0.1:5000

# File upload settings
MAX_FILE_SIZE=16777216

# Logging
LOG_LEVEL=DEBUG

# Telegram Bot Configuration
TELEGRAM_BOT_TOKEN={bot_token}

# Access Control - Comma-separated list of allowed Telegram user IDs
# IMPORTANT: Set this to restrict access to specific users only
# Leave empty to allow all users (NOT RECOMMENDED for production)
ALLOWED_USER_IDS={user_ids_input if user_ids else ''}
"""
    
    # Write .env file
    try:
        with open(env_path, 'w') as f:
            f.write(env_content)
        
        print(f"\n✅ .env file created successfully at {env_path}")
        
        if user_ids:
            print(f"🔒 Access restricted to {len(user_ids)} users:")
            for uid in user_ids:
                print(f"   • User ID: {uid}")
        else:
            print("⚠️  WARNING: Access is open to ALL users!")
            print("   This is not recommended for production use.")
        
        return True
        
    except Exception as e:
        print(f"❌ Error creating .env file: {e}")
        return False

def show_instructions():
    """Show instructions for getting user IDs"""
    print("\n📋 How to Get User IDs:")
    print("1. Run the bot with open access first:")
    print("   python scripts/run_telegram_bot.py")
    print("2. Ask users to send any message to your bot")
    print("3. Use the get_telegram_user_id.py script to get their IDs:")
    print("   python scripts/get_telegram_user_id.py")
    print("4. Add the user IDs to ALLOWED_USER_IDS in .env")
    print("5. Restart the bot with restricted access")

def main():
    """Main function"""
    print("🤖 Fyda Telegram Bot Access Control Setup")
    print("=" * 50)
    
    # Check if .env already exists
    if Path(".env").exists():
        overwrite = input("⚠️  .env file already exists. Overwrite? (y/N): ").strip().lower()
        if overwrite != 'y':
            print("❌ Setup cancelled")
            return
    
    # Create .env file
    if create_env_file():
        print("\n🎉 Setup completed successfully!")
        print("\n📝 Next steps:")
        print("1. Edit .env file if you need to add more user IDs")
        print("2. Run the bot: python scripts/run_telegram_bot.py")
        print("3. The bot will now only allow authorized users")
        
        if input("\n❓ Show instructions for getting user IDs? (y/N): ").strip().lower() == 'y':
            show_instructions()
    else:
        print("\n❌ Setup failed. Please check the errors above.")

if __name__ == "__main__":
    main()

